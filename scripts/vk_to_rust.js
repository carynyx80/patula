// Converts snarkjs verification_key.json into a Rust groth16-solana verifying key.
const fs = require("fs");
const vk = JSON.parse(fs.readFileSync(process.argv[2]));
const be = (s) => { const h = BigInt(s).toString(16).padStart(64, "0"); return Buffer.from(h, "hex"); };
const g1 = (p) => Buffer.concat([be(p[0]), be(p[1])]);
const g2 = (p) => Buffer.concat([be(p[0][1]), be(p[0][0]), be(p[1][1]), be(p[1][0])]);
const arr = (b) => "[" + [...b].join(", ") + "]";
if (JSON.stringify(vk.vk_gamma_2) === JSON.stringify(vk.vk_delta_2)) throw new Error("delta == gamma: missing phase-2 contribution");
let out = `// AUTO-GENERATED by scripts/vk_to_rust.js — do not edit. DEV setup only.
use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},
    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},
    vk_gamma_g2: ${arr(g2(vk.vk_gamma_2))},
    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},
    vk_ic: &[
${vk.IC.map((p) => "        " + arr(g1(p)) + ",").join("\n")}
    ],
    vk_commitment: None,
};
`;
fs.writeFileSync(process.argv[3], out);
console.log("wrote", process.argv[3]);
